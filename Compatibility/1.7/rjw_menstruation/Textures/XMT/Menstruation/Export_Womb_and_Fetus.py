# Run inside Krita: Tools > Scripts > Scripter > Open this file > Run.
# Uses the active document's live, unsaved artwork; no additional Python packages.
# Color-treatment/filter layers are retained. Only source PNG variants are isolated
# in a hidden clone; the original document is never changed.
# Outputs overwrite matching local runtime PNGs after all renders succeed.

# Match output paths, e.g. ["Cryptimorph/*"] or ["Cryptimorph/Breasts/*"].
INCLUDE_PATTERNS = ['Cryptimorph/*']
# Example: ["*/Empty.png", "*/Fetus/*"]
EXCLUDE_PATTERNS = []
# Export each selected texture's associated mask too, when its layer group exists.
EXPORT_SHINE_MASKS = True
# Leave None to export beside the source document; use an absolute folder if moved.
OUTPUT_ROOT = None
# True lists destinations and validates layer names without writing PNGs.
DRY_RUN = False

"""Shared source for the standalone scripts generated by BuildKritaExporters.py.

Krita API references:
https://api.kde.org/legacy/krita/html/classDocument.html
https://api.kde.org/legacy/krita/html/classNode.html
"""
from pathlib import Path
from fnmatch import fnmatchcase
import os
import tempfile


def _resolve(root, names):
    chain = []
    parent = root
    for name in names:
        matches = [node for node in parent.childNodes() if node.name() == name]
        if len(matches) != 1:
            raise RuntimeError('Expected one layer/group at: ' + ' / '.join(names) +
                               ' (missing or duplicate name: ' + name + ')')
        parent = matches[0]
        chain.append(parent)
    return chain


def _selected(relative, includes, excludes):
    return any(fnmatchcase(relative, pattern) for pattern in includes) and not any(
        fnmatchcase(relative, pattern) for pattern in excludes)


def _destination(root, relative):
    target = (root / relative).resolve()
    if root not in target.parents:
        raise RuntimeError('Export path is outside the artwork directory: ' + relative)
    return target


def _atomic_write(target, payload):
    target.parent.mkdir(parents=True, exist_ok=True)
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(dir=str(target.parent), prefix='.' + target.name + '-',
                                         suffix='.tmp', delete=False) as stream:
            temporary = Path(stream.name)
            stream.write(payload)
        os.replace(str(temporary), str(target))
    finally:
        if temporary is not None and temporary.exists():
            temporary.unlink()


def _commit(staged):
    # Only replace gameplay PNGs after every render succeeded. Roll back a partial
    # commit on write failure, retaining the previous bytes until the batch ends.
    previous = [(target, target.read_bytes() if target.exists() else None) for target, _ in staged]
    attempted = []
    try:
        for (target, source), (_, old) in zip(staged, previous):
            attempted.append((target, old))
            _atomic_write(target, source.read_bytes())
    except BaseException as export_error:
        rollback_errors = []
        for target, old in reversed(attempted):
            try:
                if old is None:
                    if target.exists():
                        target.unlink()
                else:
                    _atomic_write(target, old)
            except Exception as error:
                rollback_errors.append(str(target) + ': ' + str(error))
        if rollback_errors:
            raise RuntimeError('Export failed; some files could not be restored:\n' + '\n'.join(rollback_errors)) from export_error
        raise


def export_document(document, spec, includes, excludes, output_root=None, dry_run=False, export_masks=True):
    """Export a hidden clone of the live, possibly unsaved document.

    Only mapped PNG layers and their ancestors have visibility changed in the
    clone. Artist-created layers, filters, masks, blend modes and opacity remain
    as configured. The document open in Krita is never mutated or saved.
    """
    if document is None:
        raise RuntimeError('Open the matching ORA or KRA document in Krita first.')
    filename = document.fileName()
    if not filename or Path(filename).stem != spec['document']:
        raise RuntimeError('Activate ' + spec['document'] + '.ora or ' + spec['document'] + '.kra before running this script.')
    size = (document.width(), document.height())
    if size != tuple(spec['size']):
        raise RuntimeError('Canvas size changed. Expected ' + str(spec['size']) + '; found ' + str(size) + '.')
    root = Path(output_root).resolve() if output_root else Path(filename).resolve().parent
    if not (root / 'Cryptimorph').is_dir() or not (root / 'Default').is_dir():
        raise RuntimeError('Output root must be the Menstruation artwork folder containing Cryptimorph and Default. Set OUTPUT_ROOT if this document was moved.')

    resolved = []
    missing_mask_group = False
    for entry in spec['textures']:
        if entry.get('kind') == 'mask' and not any(node.name() == entry['nodes'][0] for node in document.rootNode().childNodes()):
            # Existing KRAs predate the optional mask tree. They can still export
            # their art; keep the runtime masks already on disk in that case.
            missing_mask_group = True
            continue
        chain = _resolve(document.rootNode(), entry['nodes'])
        resolved.append((entry, chain, _destination(root, entry['output'])))
    if missing_mask_group and export_masks:
        print('No shine mask group in this document; exporting art and preserving existing mask PNGs.')
    def included(entry):
        return (entry.get('kind') != 'mask' or export_masks) and _selected(
            entry.get('associated_texture', entry['output']), includes, excludes)
    selected = [(entry, chain, target) for entry, chain, target in resolved
                if included(entry)]
    if not selected:
        raise RuntimeError('No source textures match INCLUDE_PATTERNS / EXCLUDE_PATTERNS.')
    if len({str(target) for _, _, target in resolved}) != len(resolved):
        raise RuntimeError('Duplicate output texture paths in exporter specification.')
    if dry_run:
        for entry, _, target in selected:
            print('Would export: ' + entry['output'] + ' -> ' + str(target))
        return len(selected)

    from krita import InfoObject
    from PyQt5.QtGui import QImage
    config = InfoObject()
    for name, value in [('alpha', True), ('compression', 6), ('forceSRGB', True),
                        ('indexed', False), ('interlaced', False), ('saveSRGBProfile', True)]:
        config.setProperty(name, value)
    # Finish pending brush/filter jobs before copying the live image.
    document.waitForDone()
    clone = document.clone()
    if clone is None:
        raise RuntimeError('Krita could not clone the document.')
    try:
        clone.setBatchmode(True)
        clone.waitForDone()
        chains = [(entry, _resolve(clone.rootNode(), entry['nodes']), target) for entry, _, target in resolved]
        controlled = {}
        for entry, chain, _ in chains:
            for depth, node in enumerate(chain, 1):
                controlled[tuple(entry['nodes'][:depth])] = node
        # Detect a source group that accidentally contains another mapped source.
        leaf_paths = [tuple(entry['nodes']) for entry, _, _ in chains]
        for path in leaf_paths:
            if any(len(other) > len(path) and other[:len(path)] == path for other in leaf_paths):
                raise RuntimeError('Mapped source layers cannot contain other mapped source layers: ' + ' / '.join(path))
        for node in controlled.values():
            node.setVisible(False)
        previous_chain = []
        with tempfile.TemporaryDirectory(prefix='XMT_KritaExport_') as temporary:
            staged = []
            for entry, chain, target in chains:
                if not included(entry):
                    continue
                for node in previous_chain:
                    node.setVisible(False)
                for node in chain:
                    node.setVisible(True)
                previous_chain = chain
                clone.refreshProjection()
                clone.waitForDone()
                stage = Path(temporary) / ('%04d.png' % len(staged))
                x, y, width, height = entry['rect']
                is_mask = entry.get('kind') == 'mask'
                if is_mask:
                    # Read only the mask node's projection, not the whole-document
                    # composite: global ColorHue/filter layers must not tint masks.
                    node = chain[-1]
                    if node.colorModel() != 'RGBA' or node.colorDepth() != 'U8':
                        raise RuntimeError('Shine masks must be RGBA, 8-bit: ' + entry['output'])
                    pixels = bytearray(node.projectionPixelData(x, y, width, height))
                    if len(pixels) != width * height * 4:
                        raise RuntimeError('Invalid mask pixel rectangle: ' + entry['output'])
                    # Krita integer RGBA data is BGRA. Bake grayscale intensity into
                    # alpha so painting black removes shine and white restores it.
                    for offset in range(0, len(pixels), 4):
                        pixels[offset + 3] = (max(pixels[offset:offset + 3]) * pixels[offset + 3] + 127) // 255
                        pixels[offset:offset + 3] = b'\xff\xff\xff'
                    image = QImage(bytes(pixels), width, height, width * 4, QImage.Format_ARGB32).copy()
                    if not image.save(str(stage), 'PNG'):
                        raise RuntimeError('Could not save mask ' + entry['output'])
                else:
                    if not clone.exportImage(str(stage), config):
                        raise RuntimeError('Krita failed to export ' + entry['output'])
                    clone.waitForDone()
                # Small transparent placeholders occupy only part of the canvas.
                # Crop back to the original file rectangle without rescaling pixels.
                if not is_mask and (x, y, width, height) != (0, 0, size[0], size[1]):
                    image = QImage(str(stage))
                    if image.isNull() or not image.copy(x, y, width, height).save(str(stage), 'PNG'):
                        raise RuntimeError('Could not crop ' + entry['output'])
                image = QImage(str(stage))
                if image.isNull() or image.width() != width or image.height() != height or not image.hasAlphaChannel():
                    raise RuntimeError('PNG dimensions or alpha are incorrect: ' + entry['output'])
                staged.append((target, stage))
                if len(staged) % 25 == 0:
                    print('Rendered %d / %d textures' % (len(staged), len(selected)))
            _commit(staged)
        print('Exported %d textures. The open document and unrelated layer visibility were unchanged.' % len(selected))
        return len(selected)
    finally:
        # This hidden clone has no views and is never saved as the user's source.
        clone.close()


def run_export(spec):
    from krita import Krita
    return export_document(Krita.instance().activeDocument(), spec, INCLUDE_PATTERNS,
                           EXCLUDE_PATTERNS, OUTPUT_ROOT, DRY_RUN, EXPORT_SHINE_MASKS)


